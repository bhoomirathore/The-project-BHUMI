// Document Service
// Authoritative hashing is strictly performed server-side per architectural rules.

import apiClient, { isMockMode } from '../api/client';
import mockStore from '../api/mock/store';

/**
 * In mock mode, compute SHA-256 of the exact file bytes using Web Crypto API.
 * NOTE: Client-side validation & hashing is for mock simulation and immediate feedback.
 * Authoritative security validation (file type, size limits, and magic byte verification)
 * must also strictly be performed server-side.
 */
export async function computeFileHash(file) {
  try {
    if (typeof crypto !== 'undefined' && crypto.subtle) {
      const arrayBuffer = await file.arrayBuffer();
      const hashBuffer = await crypto.subtle.digest('SHA-256', arrayBuffer);
      const hashArray = Array.from(new Uint8Array(hashBuffer));
      const hashHex = hashArray.map((b) => b.toString(16).padStart(2, '0')).join('');
      return `0x${hashHex}`;
    }
  } catch (err) {
    console.warn('Web Crypto hash computation failed, using fallback', err);
  }
  return `0x${Array.from({ length: 64 }, () => Math.floor(Math.random() * 16).toString(16)).join('')}`;
}

export const documentService = {
  async uploadDocument(file, type) {
    if (isMockMode()) {
      // In mock mode, compute real SHA-256 of file bytes with Web Crypto API
      const hash = await computeFileHash(file);
      return {
        docId: `doc-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
        type,
        fileName: file.name,
        size: file.size,
        fileSize: file.size,
        mimeType: file.type || 'application/octet-stream',
        hash,
        integrity: 'MATCH',
      };
    }
    // TODO(api-contract): POST /documents/upload multipart/form-data with file and type
    const formData = new FormData();
    formData.append('file', file);
    formData.append('type', type);
    return await apiClient.post('/documents/upload', formData, {
      headers: { 'Content-Type': undefined },
    });
  },

  async verifyIntegrity(docId, applicationId) {
    if (isMockMode()) {
      return await mockStore.verifyDocumentIntegrity(docId, applicationId);
    }
    // TODO(api-contract): GET /documents/:docId/integrity?applicationId=:applicationId
    return await apiClient.get(
      `/documents/${encodeURIComponent(docId)}/integrity?applicationId=${encodeURIComponent(applicationId)}`
    );
  },

  async downloadERegistry(applicationId) {
    if (isMockMode()) {
      return {
        isMockNotice: true,
        message: 'E-Registry PDF is generated by the backend and is not available in prototype mode.',
      };
    }
    // TODO(api-contract): GET /applications/:applicationId/e-registry/download
    return await apiClient.get(`/applications/${encodeURIComponent(applicationId)}/e-registry/download`);
  },
};

export default documentService;
